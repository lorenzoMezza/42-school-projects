#include <unistd.h>

void	ft_putnbr(int nb)
{
	char	cifra;

	if (nb == -2147483648)
	{
		write(1, "-2147483648", 11);
		return ;
	}
	if (nb < 0)
	{
		write(1, "-", 1);
		nb = -nb;
	}
	if (nb >= 10)
	{
		ft_putnbr(nb / 10);
		cifra = (nb % 10) + '0';
		write(1, &cifra, 1);
	}
	else
	{
		cifra = nb + '0';
		write(1, &cifra, 1);
	}
}
